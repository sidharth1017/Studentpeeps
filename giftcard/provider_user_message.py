"""Map raw provider / HTTP errors to short customer-facing copy."""
from __future__ import annotations

import html
import json
import re
from typing import Optional

_MAX_PLAIN_LEN = 280

_HTTP_PREFIX = re.compile(r"^HTTP\s+(\d{3})\s*:\s*(.*)", re.DOTALL | re.IGNORECASE)
_HTML_MARKERS = re.compile(r"<!DOCTYPE|<html|<HTML|<TITLE|</body>", re.IGNORECASE)
_TAG = re.compile(r"<[a-zA-Z]")


def user_message_for_provider_error(raw: Optional[str]) -> Optional[str]:
    if raw is None:
        return None
    text = str(raw).strip()
    if not text:
        return None

    match = _HTTP_PREFIX.match(text)
    if match:
        return _message_for_http(int(match.group(1)), match.group(2))

    if _HTML_MARKERS.search(text) or _looks_like_markup(text):
        return _message_for_http(None, text)

    if text.startswith("{"):
        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            data = None
        if isinstance(data, dict):
            for key in ("message", "error", "errorMessage", "description"):
                msg = data.get(key)
                if isinstance(msg, str) and msg.strip():
                    nested = user_message_for_provider_error(msg.strip())
                    if nested:
                        return nested

    if len(text) > _MAX_PLAIN_LEN:
        return _generic_partner_issue(None)

    return text


def _looks_like_markup(text: str) -> bool:
    return bool(_TAG.search(text))


def _strip_html(text: str) -> str:
    text = re.sub(r"<script[^>]*>.*?</script>", " ", text, flags=re.DOTALL | re.IGNORECASE)
    text = re.sub(r"<style[^>]*>.*?</style>", " ", text, flags=re.DOTALL | re.IGNORECASE)
    text = re.sub(r"<[^>]+>", " ", text)
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def _message_for_http(code: Optional[int], body: str) -> str:
    plain = _strip_html(body)
    plain_lower = plain.lower()

    if (
        code == 403
        or "403 error" in plain_lower
        or "request blocked" in plain_lower
        or "could not be satisfied" in plain_lower
        or "generated by cloudfront" in plain_lower
    ):
        return (
            "Our gift card partner couldn’t accept the request right now—often a temporary "
            "network or security block. Your payment is safe; any refund will return to your "
            "original payment method."
        )

    if code == 401:
        return (
            "We couldn’t authenticate with our gift card partner. Our team has been notified. "
            "Your payment is safe and any refund will return to your original payment method."
        )

    if code is not None and code >= 500:
        return _generic_partner_issue(code)

    if code == 408 or "timeout" in plain_lower or "timed out" in plain_lower:
        return (
            "The connection to our gift card partner timed out before your card was created. "
            "Your payment is safe; we’ll deliver the card or refund you if we can’t complete the order."
        )

    if plain and len(plain) <= 200 and not _looks_like_markup(plain):
        return plain

    return _generic_partner_issue(code)


def _generic_partner_issue(code: Optional[int]) -> str:
    base = (
        "We couldn’t finish creating your gift card with our partner. "
        "Your payment is safe and any refund will return to your original payment method."
    )
    if code is not None:
        return f"{base} (reference code {code})."
    return base
